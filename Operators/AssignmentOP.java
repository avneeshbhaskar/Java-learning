package Operators;
public class AssignmentOP {
    public static void main(String[] args) {
        int a = 10;
        // a = a + 10; We can also write it as given
        a += 10;
        int b = 5;
        // b = b - 5; We can also write it as given 
        // b -= 5;
        // b /= 2;
        // b *= 5;
        b %= 2;
        System.out.println(a);
        System.out.println(b);
    }
    
}
